pub fn glyph(ch: u8) -> &'static [u8; 8] {
    let idx = if ch < 128 { ch as usize } else { b'?' as usize };
    &FONT8X8[idx]
}

/// Plot the ink of one glyph. `plot` receives offsets inside the scaled cell.
pub fn paint_glyph(ch: u8, scale: u32, mut plot: impl FnMut(u32, u32)) {
    let scale = scale.max(1);
    let bits = glyph(ch);
    for row in 0..8u32 {
        let line = bits[row as usize];
        for col in 0..8u32 {
            if line & (1 << col) == 0 {
                continue;
            }
            for sy in 0..scale {
                for sx in 0..scale {
                    plot(col * scale + sx, row * scale + sy);
                }
            }
        }
    }
}

